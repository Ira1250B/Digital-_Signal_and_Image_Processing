import matplotlib.pyplot as plt
import cv2
import numpy as np

image1=cv2.imread(r"C:\Users\bhoga\Downloads\Picture1-6.png",0)
image2=cv2.imread(r"C:\Users\bhoga\Downloads\Picture2-6.jpg",0)
image3=cv2.imread(r"C:\Users\bhoga\Downloads\Picture3-6.png",0)
#perform closing to remove holes 
kernel = np.ones((5, 5), np.uint8)
img1=cv2.erode(image1,kernel,iterations=2)
plt.figure(figsize=(8,10))
plt.subplot(1,2,1)
plt.imshow(image1,cmap='gray')
plt.axis('off')
plt.title("Original Image")
plt.subplot(1,2,2)
plt.imshow(img1,cmap='gray')
plt.axis('off')
plt.title("improved image")
plt.show()
#performing eroision for second image
kernel1 = np.ones((3,2), np.uint8)
img2=cv2.morphologyEx(image2,cv2.MORPH_OPEN,kernel1)
plt.figure(figsize=(8,10))
plt.subplot(1,2,1)
plt.imshow(image2,cmap='gray')
plt.axis('off')
plt.title("Original Image")
plt.subplot(1,2,2)
plt.imshow(img2,cmap='gray')
plt.axis('off')
plt.title("improved image")
plt.show()
#performing opening on the third image for rmoval of noise
kernel2 = np.ones((3, 3), np.uint8)
img3=cv2.morphologyEx(image3,cv2.MORPH_OPEN,kernel2)
plt.figure(figsize=(8,10))
plt.subplot(1,2,1)
plt.imshow(image3,cmap='gray')
plt.axis('off')
plt.title("Original Image")
plt.subplot(1,2,2)
plt.imshow(img3,cmap='gray')
plt.axis('off')
plt.title("improved image")
plt.show()